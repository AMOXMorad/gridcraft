//! Smart suggestion engine for spreadsheet insights.
//!
//! Analyzes column data patterns, detects types (numeric, dates, currency, text),
//! and generates actionable suggestions (total rows, charts, conditional formatting, pivot tables).

use std::collections::HashSet;

use serde::{Deserialize, Serialize};
use serde_json::json;

use crate::assistant::SheetContext;

/// The category of a smart suggestion.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum SuggestionKind {
    /// Add or toggle a summary total row.
    TotalRow,
    /// Insert a recommended visualization.
    Chart,
    /// Apply data bars, color scales, or highlight rules.
    ConditionalFormatting,
    /// Generate an aggregated PivotTable report.
    PivotTable,
}

/// A smart suggestion generated by the AI engine.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Suggestion {
    /// The suggestion category.
    pub kind: SuggestionKind,
    /// Human-readable short title.
    pub title: String,
    /// Detailed description of the insight or recommendation.
    pub description: String,
    /// Engine command identifier to execute (e.g. `"table.totalRow"`, `"insert.chart"`).
    pub command: String,
    /// JSON parameters to pass to the engine command.
    pub params: serde_json::Value,
}

/// Inferred data type of a spreadsheet column.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum ColumnDataType {
    /// Standard numbers (integers, floating point).
    Numeric,
    /// Monetary values (e.g. `$100`, `€45.50`).
    Currency,
    /// Percentage values (e.g. `25%`, `12.5%`).
    Percentage,
    /// Dates (e.g. `2026-01-15`, `01/15/2026`).
    Date,
    /// Categorical or descriptive text strings.
    Text,
    /// Empty or unpopulated column.
    Empty,
}

/// Analysis summary for a single column.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct ColumnAnalysis {
    /// 0-based column index.
    pub index: usize,
    /// Column header or title.
    pub header: String,
    /// Inferred primary data type.
    pub data_type: ColumnDataType,
    /// Number of sampled values.
    pub sample_count: usize,
    /// Number of unique distinct values in sample.
    pub distinct_count: usize,
    /// Minimum numeric value if applicable.
    pub min_numeric: Option<f64>,
    /// Maximum numeric value if applicable.
    pub max_numeric: Option<f64>,
    /// Sum of numeric values if applicable.
    pub sum_numeric: Option<f64>,
}

/// Analyzes a sheet's structure and sample data to produce a list of smart suggestions.
pub fn analyze_sheet(sheet: &SheetContext) -> Vec<Suggestion> {
    let columns = analyze_columns(sheet);
    let mut suggestions = Vec::new();

    let num_cols: Vec<&ColumnAnalysis> =
        columns.iter().filter(|c| matches!(c.data_type, ColumnDataType::Numeric | ColumnDataType::Currency)).collect();
    let text_cols: Vec<&ColumnAnalysis> = columns.iter().filter(|c| c.data_type == ColumnDataType::Text).collect();
    let date_cols: Vec<&ColumnAnalysis> = columns.iter().filter(|c| c.data_type == ColumnDataType::Date).collect();

    // 1. Suggest Total Row if there are numeric or currency columns
    if !num_cols.is_empty() {
        let headers: Vec<&str> = num_cols.iter().map(|c| c.header.as_str()).collect();
        suggestions.push(Suggestion {
            kind: SuggestionKind::TotalRow,
            title: "Add Total Row".into(),
            description: format!("Add a summary total row calculating the sum of {}.", headers.join(", ")),
            command: "table.totalRow".into(),
            params: json!({ "on": true }),
        });
    }

    // 2. Suggest Charts
    // Case A: Dates + Numbers -> Line Chart
    if let (Some(date_col), Some(num_col)) = (date_cols.first(), num_cols.first()) {
        suggestions.push(Suggestion {
            kind: SuggestionKind::Chart,
            title: format!("Trend Line Chart for {}", num_col.header),
            description: format!("Plot {} over {} as a line chart to reveal trends over time.", num_col.header, date_col.header),
            command: "insert.chart".into(),
            params: json!({
                "type": "line",
                "title": format!("{} over Time", num_col.header),
            }),
        });
    }

    // Case B: Categories + Numbers -> Column Chart
    if let (Some(cat_col), Some(num_col)) = (text_cols.first(), num_cols.first()) {
        suggestions.push(Suggestion {
            kind: SuggestionKind::Chart,
            title: format!("Column Chart for {} by {}", num_col.header, cat_col.header),
            description: format!("Compare {} across {} using a column chart.", num_col.header, cat_col.header),
            command: "insert.chart".into(),
            params: json!({
                "type": "column",
                "title": format!("{} by {}", num_col.header, cat_col.header),
            }),
        });

        // Case C: Small number of categories (2 to 7) -> Pie Chart
        if cat_col.distinct_count >= 2 && cat_col.distinct_count <= 7 {
            suggestions.push(Suggestion {
                kind: SuggestionKind::Chart,
                title: format!("Pie Chart: {} Distribution", cat_col.header),
                description: format!("Visualize the proportion of {} by {}.", num_col.header, cat_col.header),
                command: "insert.chart".into(),
                params: json!({
                    "type": "pie",
                    "title": format!("{} Breakdown", cat_col.header),
                }),
            });
        }
    }

    // 3. Conditional Formatting
    if let Some(num_col) = num_cols.first() {
        suggestions.push(Suggestion {
            kind: SuggestionKind::ConditionalFormatting,
            title: format!("Data Bars for {}", num_col.header),
            description: format!("Visualize relative magnitudes in column {} using data bars.", num_col.header),
            command: "home.conditionalFormat".into(),
            params: json!({
                "rule": {
                    "type": "dataBar",
                    "color": "blue"
                }
            }),
        });
    }

    // Check for status words in text columns
    for col in &text_cols {
        let has_status = sheet
            .sample_data
            .iter()
            .filter_map(|row| row.get(col.index))
            .any(|val| matches!(val.to_ascii_lowercase().as_str(), "fail" | "error" | "pending" | "overdue" | "delayed"));

        if has_status {
            suggestions.push(Suggestion {
                kind: SuggestionKind::ConditionalFormatting,
                title: format!("Highlight Issues in {}", col.header),
                description: format!("Apply conditional formatting to highlight warnings or failures in {}.", col.header),
                command: "home.conditionalFormat".into(),
                params: json!({
                    "rule": {
                        "type": "containsText",
                        "text": "Fail",
                        "preset": "lightRedFillDarkRedText"
                    }
                }),
            });
            break;
        }
    }

    // 4. Suggest Pivot Table if we have both categorical and numeric columns
    if let (Some(cat_col), Some(num_col)) = (text_cols.first(), num_cols.first())
        && (sheet.sample_data.len() >= 3 || sheet.total_rows >= 3)
    {
        suggestions.push(Suggestion {
            kind: SuggestionKind::PivotTable,
            title: format!("PivotTable: {} by {}", num_col.header, cat_col.header),
            description: format!("Summarize and aggregate total {} grouped by {}.", num_col.header, cat_col.header),
            command: "insert.pivotTable".into(),
            params: json!({
                "rows": [cat_col.header],
                "values": [{ "field": num_col.header, "func": "sum" }]
            }),
        });
    }

    suggestions
}

/// Analyzes each column in a sheet's headers and sample data.
pub fn analyze_columns(sheet: &SheetContext) -> Vec<ColumnAnalysis> {
    let col_count = sheet.headers.len().max(sheet.sample_data.iter().map(|r| r.len()).max().unwrap_or(0)).min(gridcraft_core::MAX_COLS as usize);

    let mut out = Vec::with_capacity(col_count);

    for col_idx in 0..col_count {
        let header =
            sheet.headers.get(col_idx).cloned().unwrap_or_else(|| format!("Column {}", gridcraft_core::addr::col_to_letters(col_idx as u32)));

        let mut values = Vec::new();
        let mut distinct = HashSet::new();

        for row in &sheet.sample_data {
            if let Some(val) = row.get(col_idx) {
                let trimmed = val.trim();
                if !trimmed.is_empty() {
                    values.push(trimmed);
                    distinct.insert(trimmed);
                }
            }
        }

        let data_type = infer_column_type(&values);

        let (min_numeric, max_numeric, sum_numeric) =
            if matches!(data_type, ColumnDataType::Numeric | ColumnDataType::Currency | ColumnDataType::Percentage) {
                let mut min_val: Option<f64> = None;
                let mut max_val: Option<f64> = None;
                let mut sum_val = 0.0;
                let mut count = 0;

                for val in &values {
                    if let Some(num) = parse_numeric_value(val) {
                        min_val = Some(min_val.map_or(num, |m| m.min(num)));
                        max_val = Some(max_val.map_or(num, |m| m.max(num)));
                        sum_val += num;
                        count += 1;
                    }
                }

                if count > 0 { (min_val, max_val, Some(sum_val)) } else { (None, None, None) }
            } else {
                (None, None, None)
            };

        out.push(ColumnAnalysis {
            index: col_idx,
            header,
            data_type,
            sample_count: values.len(),
            distinct_count: distinct.len(),
            min_numeric,
            max_numeric,
            sum_numeric,
        });
    }

    out
}

/// Infers the predominant data type of a column from sampled string values.
pub fn infer_column_type(values: &[&str]) -> ColumnDataType {
    if values.is_empty() {
        return ColumnDataType::Empty;
    }

    let mut num_count = 0;
    let mut currency_count = 0;
    let mut percent_count = 0;
    let mut date_count = 0;
    let mut text_count = 0;

    for &v in values {
        let t = v.trim();
        if t.is_empty() {
            continue;
        }

        if is_currency(t) {
            currency_count += 1;
        } else if is_percentage(t) {
            percent_count += 1;
        } else if is_date(t) {
            date_count += 1;
        } else if parse_numeric_value(t).is_some() {
            num_count += 1;
        } else {
            text_count += 1;
        }
    }

    let total = (num_count + currency_count + percent_count + date_count + text_count).max(1);

    if currency_count * 2 >= total {
        ColumnDataType::Currency
    } else if percent_count * 2 >= total {
        ColumnDataType::Percentage
    } else if date_count * 2 >= total {
        ColumnDataType::Date
    } else if (num_count + currency_count) * 2 >= total {
        ColumnDataType::Numeric
    } else {
        ColumnDataType::Text
    }
}

/// Tests if a string represents currency (e.g. `$100`, `€45.50`, `£1,200`).
fn is_currency(s: &str) -> bool {
    let t = s.trim();
    let symbols = ['$', '€', '£', '¥'];
    let has_symbol = symbols.iter().any(|&sym| t.starts_with(sym) || t.ends_with(sym));
    if !has_symbol {
        return false;
    }

    let stripped = t.trim_matches(['$', '€', '£', '¥', ' ']).replace(',', "");
    stripped.parse::<f64>().is_ok()
}

/// Tests if a string represents a percentage (e.g. `15%`, `2.5%`).
fn is_percentage(s: &str) -> bool {
    let t = s.trim();
    if !t.ends_with('%') {
        return false;
    }
    let stripped = t.trim_end_matches(['%', ' ']).replace(',', "");
    stripped.parse::<f64>().is_ok()
}

/// Tests if a string represents a date format (e.g. `2026-01-15`, `2026/01/15`, `01/15/2026`).
fn is_date(s: &str) -> bool {
    let t = s.trim();
    if t.len() < 8 || t.len() > 10 {
        return false;
    }

    let parts: Vec<&str> = if t.contains('-') {
        t.split('-').collect()
    } else if t.contains('/') {
        t.split('/').collect()
    } else {
        return false;
    };

    if parts.len() != 3 {
        return false;
    }

    let all_numeric = parts.iter().all(|p| p.parse::<u32>().is_ok());
    if !all_numeric {
        return false;
    }

    true
}

/// Parses a number string, ignoring commas and currency symbols.
fn parse_numeric_value(s: &str) -> Option<f64> {
    let t = s.trim().trim_matches(['$', '€', '£', '¥', '%', ' ']).replace(',', "");
    t.parse::<f64>().ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn infers_column_types() {
        assert_eq!(infer_column_type(&["100", "250.5", "42"]), ColumnDataType::Numeric);
        assert_eq!(infer_column_type(&["$100.00", "$250.50", "$42.10"]), ColumnDataType::Currency);
        assert_eq!(infer_column_type(&["10%", "25.5%", "99%"]), ColumnDataType::Percentage);
        assert_eq!(infer_column_type(&["2026-01-01", "2026-02-15", "2026-03-30"]), ColumnDataType::Date);
        assert_eq!(infer_column_type(&["North", "South", "East", "West"]), ColumnDataType::Text);
        assert_eq!(infer_column_type(&[]), ColumnDataType::Empty);
    }

    #[test]
    fn generates_suggestions_for_sales_sheet() {
        let sheet = SheetContext {
            name: "Sales".into(),
            used_range: Some("A1:C5".into()),
            headers: vec!["Date".into(), "Region".into(), "Revenue".into()],
            sample_data: vec![
                vec!["2026-01-01".into(), "North".into(), "$1500".into()],
                vec!["2026-01-02".into(), "South".into(), "$2300".into()],
                vec!["2026-01-03".into(), "North".into(), "$1800".into()],
                vec!["2026-01-04".into(), "West".into(), "$3100".into()],
            ],
            total_rows: 5,
            total_cols: 3,
        };

        let suggestions = analyze_sheet(&sheet);
        assert!(!suggestions.is_empty());

        let has_total = suggestions.iter().any(|s| s.kind == SuggestionKind::TotalRow);
        let has_chart = suggestions.iter().any(|s| s.kind == SuggestionKind::Chart);
        let has_cf = suggestions.iter().any(|s| s.kind == SuggestionKind::ConditionalFormatting);
        let has_pivot = suggestions.iter().any(|s| s.kind == SuggestionKind::PivotTable);

        assert!(has_total);
        assert!(has_chart);
        assert!(has_cf);
        assert!(has_pivot);
    }
}
